function addLocalizedDetails(
  language: WestLanguage,
  profiles: Record<string, LocalizedToolProfileBase>,
): Record<string, LocalizedToolProfile> {
  const details = localizedDetails[language];
  const entries = Object.entries(profiles);

  if (details.length !== entries.length) {
    throw new Error(`Incomplete localized details for ${language}`);
  }

  return Object.fromEntries(entries.map(([slug, profile], index) => {
    const [example, limitation] = details[index];
    return [slug, { ...profile, example, limitation }];
  }));
}

